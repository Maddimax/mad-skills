#!/usr/bin/env python3
"""Read-only status report for the review-attentionsetself scheduled task.

Fetches, in parallel, everything the task needs to decide what to do and prints
one compact line per change plus an action hint. It never writes to Gerrit.

  Mine  (owner:self status:open): mergeable, unresolved threads, bot/precheck state,
        whether a parent in the relation chain is still open (stacked).
  Theirs(attention:self status:open, not mine): bot review state for the current
        patch set, precheck state, votes -> READY_FOR_PLUS2 / NEEDS_BOT / ...

Usage: gerrit-attention-report.py [--full] [--json] [--all]
       gerrit-attention-report.py --start-bot N [N...]   (REST; once per patch set, never re-requests)
       gerrit-attention-report.py --patch N              (unified diff of N's current patch set)
--only N [N...] restricts the output to those changes (combine with --full).
--full prints commit message, files, attention reasons, unresolved threads with
their reply_to ids, precheck failure text and recent messages per change.
Credentials: ~/.gerrit (git-config format http.user / http.pwd).
"""
import base64
import concurrent.futures as cf
import datetime
import json
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request

HOST = "https://codereview.qt-project.org"
BOT = "Qt Review Bot"
OPTS = ["CURRENT_REVISION", "MESSAGES", "DETAILED_LABELS", "DETAILED_ACCOUNTS", "CURRENT_COMMIT"]


def creds():
    def get(key):
        return subprocess.check_output(
            ["git", "config", "-f", str(__import__("pathlib").Path.home() / ".gerrit"), key],
            text=True).strip()
    token = base64.b64encode(f"{get('http.user')}:{get('http.pwd')}".encode()).decode()
    return {"Authorization": "Basic " + token}


AUTH = creds()


def api(path, method="GET"):
    req = urllib.request.Request(HOST + "/a" + path, headers=AUTH, method=method)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            body = r.read().decode()
    except urllib.error.HTTPError as e:
        return {"_error": f"HTTP {e.code}"}
    except Exception as e:  # network
        return {"_error": str(e)}
    return json.loads(body[4:] if body.startswith(")]}'") else body)


def query(q):
    qs = urllib.parse.urlencode([("q", q), ("n", "100")] + [("o", o) for o in OPTS])
    return api("/changes/?" + qs)


def precheck_state(ch, ps):
    """Latest Qt CI Bot precheck result for patch set ps: passed/failed/pending/none."""
    state = "none"
    for m in ch.get("messages", []):
        if m.get("_revision_number") != ps:
            continue
        text = m.get("message", "")
        author = m.get("author", {}).get("name", "")
        if "Precheck requested" in text:
            state = "pending"
        elif "Qt CI Bot" in author and "Quick Check" in text:
            if "Quick Check: Passed" in text:
                state = "passed"
            elif "Quick Check: Failed" in text:
                state = "failed"
            elif state == "none":
                state = "pending"
    return state


def bot_state(ch, ps, jobs):
    """Bot review of patch set ps: clean / findings / reviewed / job:<status> / none.
    A +1/-1 from the bot that Gerrit copied over a trivial rebase counts."""
    for v in ch["labels"].get("Code-Review", {}).get("all", []):
        if BOT in v.get("name", "") and v.get("value"):
            return "clean" if v["value"] > 0 else "findings"
    for m in ch.get("messages", []):
        if m.get("_revision_number") == ps and m.get("tag") == "autogenerated:qt-code-review":
            if "Code-Review+1" in m["message"]:
                return "clean"
            if "Code-Review-1" in m["message"]:
                return "findings"
            return "reviewed"
    if isinstance(jobs, list):
        for j in jobs:
            if any(c.get("patchset") == ps and c.get("number") == ch["_number"]
                   for c in j.get("changes", [])):
                return "job:" + j.get("status", "?")
    return "none"


MSG_CHARS = 1500


def unresolved_threads(n):
    """Unresolved comment threads with the id to reply to (the thread's last comment)."""
    data = api(f"/changes/{n}/comments")
    if not isinstance(data, dict) or "_error" in data:
        return []
    out = []
    for path, comments in data.items():
        by_id = {c["id"]: c for c in comments}
        replied = {c["in_reply_to"] for c in comments if c.get("in_reply_to")}
        for last in comments:
            if last["id"] in replied or not last.get("unresolved"):
                continue  # not a thread end, or resolved
            chain, c = [], last
            while c:
                chain.append(c)
                c = by_id.get(c.get("in_reply_to"))
            chain.reverse()
            out.append({
                "reply_to": last["id"], "file": path, "line": chain[0].get("line"),
                "range": chain[0].get("range"), "patchset": chain[0].get("patch_set"),
                "comments": [{"author": c.get("author", {}).get("name", "?"), "text": c["message"]}
                             for c in chain]})
    return out


def analyse(ch):
    n = ch["_number"]
    ps = ch["revisions"][ch["current_revision"]]["_number"]
    jobs = api(f"/changes/{n}/qt-code-review~jobs")
    info = {
        "number": n,
        "subject": ch["subject"],
        "owner": ch["owner"].get("name", ""),
        "branch": ch["branch"],
        "patchset": ps,
        "wip": ch.get("work_in_progress", False) or ch["subject"].startswith("WIP"),
        "age_days": (datetime.datetime.now(datetime.timezone.utc).replace(tzinfo=None) - datetime.datetime.strptime(
            ch["updated"][:19], "%Y-%m-%d %H:%M:%S")).days,
        "unresolved": ch.get("unresolved_comment_count", 0),
        "bot": bot_state(ch, ps, jobs),
        "precheck": precheck_state(ch, ps),
        "verified": [v.get("value") for v in ch["labels"].get("Verified", {}).get("all", [])
                     if v.get("value")],
        "code_review": {v["name"]: v["value"] for v in ch["labels"].get("Code-Review", {}).get("all", [])
                        if v.get("value")},
        "mergeable": api(f"/changes/{n}/revisions/current/mergeable").get("mergeable"),
    }
    rev = ch["revisions"][ch["current_revision"]]
    info.update({
        "url": f"{HOST}/c/{ch['project']}/+/{n}",
        "project": ch["project"],
        "sha": ch["current_revision"],
        "parent_sha": [p["commit"] for p in rev.get("commit", {}).get("parents", [])],
        "commit_message": rev.get("commit", {}).get("message", ""),
        "attention_set": [f"{a['account'].get('name', '?')}: {a.get('reason', '')}"
                          for a in ch.get("attention_set", {}).values()],
        "reviewers": [r.get("name", "?") for r in ch.get("reviewers", {}).get("REVIEWER", [])],
        "votes": {lab: {v["name"]: v["value"] for v in d.get("all", []) if v.get("value")}
                  for lab, d in ch["labels"].items()},
        "bot_jobs": [{"id": j.get("id"), "status": j.get("status"),
                      "patchsets": [c.get("patchset") for c in j.get("changes", [])]}
                     for j in jobs] if isinstance(jobs, list) else [],
        "messages": [{"ps": m.get("_revision_number"), "author": m.get("author", {}).get("name", "?"),
                      "date": m["date"][:16], "tag": m.get("tag", ""),
                      "text": m["message"][:MSG_CHARS]} for m in ch.get("messages", [])[-8:]],
    })
    files = api(f"/changes/{n}/revisions/current/files")
    info["files"] = ({f: f"+{d.get('lines_inserted', 0)}/-{d.get('lines_deleted', 0)}"
                      for f, d in files.items() if f != "/COMMIT_MSG"}
                     if isinstance(files, dict) and "_error" not in files else {})
    info["unresolved_threads"] = unresolved_threads(n) if info["unresolved"] else []
    if info["precheck"] == "failed":
        info["precheck_failure"] = next((m["text"] for m in reversed(info["messages"])
                                         if "Quick Check: Failed" in m["text"]), "")
    rel = api(f"/changes/{n}/revisions/current/related").get("changes", [])
    cur = next((i for i, r in enumerate(rel) if r["_change_number"] == n), None)
    # related is ordered newest-first: entries after ours are parents
    info["open_parents"] = [r["_change_number"] for r in (rel[cur + 1:] if cur is not None else [])
                            if r.get("status") == "NEW"]
    info["open_children"] = [r["_change_number"] for r in (rel[:cur] if cur is not None else [])
                             if r.get("status") == "NEW"]
    return info


STALE_DAYS = 21


def hint(i, mine):
    if mine and not i["attention"] and (i["wip"] or i["age_days"] > STALE_DAYS):
        return "skip (WIP or untouched for >%dd)" % STALE_DAYS
    if mine:
        if i["mergeable"] is False:
            if i["open_parents"]:
                return "CONFLICT-OR-WAITING-ON-PARENT (check git range-diff after stack rebase)"
            return "CONFLICT: rebase, resolve, push, start bot"
        if i["unresolved"]:
            return "FIXES-REQUESTED: unresolved threads"
        if i["bot"] == "findings":
            return "FIXES-REQUESTED: bot findings"
        if i["bot"] == "none":
            return "NEEDS_BOT"
        if i["bot"] == "clean" and i["precheck"] == "passed":
            return "READY: waiting for another reviewer's +2"
        return "waiting"
    if i["wip"]:
        return "wip: skip"
    if i["bot"] == "none":
        return "NEEDS_BOT"
    if i["bot"].startswith("job:"):
        return "bot running: wait"
    if i["bot"] == "findings":
        return "bot findings: leave alone, list"
    if i["precheck"] == "none":
        return "NEEDS_PRECHECK (request once, hold +2)"
    if i["precheck"] in ("pending", "failed"):
        return f"precheck {i['precheck']}: hold +2, list"
    if 2 in i["code_review"].values():
        return "already +2"
    return "READY_FOR_PLUS2"


def start_bot(n):
    """Start the Qt Code Review bot on the current patch set, once."""
    ch = api(f"/changes/{n}?o=CURRENT_REVISION")
    ps = ch["revisions"][ch["current_revision"]]["_number"]
    jobs = api(f"/changes/{n}/qt-code-review~jobs")
    for j in jobs if isinstance(jobs, list) else []:
        if any(c.get("patchset") == ps for c in j.get("changes", [])):
            return f"{n}: not started, a bot job ({j.get('status')}) already exists for ps{ps}"
    opts = api(f"/changes/{n}/revisions/current/qt-code-review~review-options")
    body = {"scope": "current", "changes": [], "guidance": opts.get("detected_guidance", []),
            "effort": "auto", "focus": None, "vote": True, "whole": []}
    req = urllib.request.Request(HOST + f"/a/changes/{n}/revisions/{ps}/qt-code-review~review",
                                 data=json.dumps(body).encode(), method="POST",
                                 headers={**AUTH, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            r.read()
        return f"{n}: bot queued on ps{ps} (guidance {body['guidance']})"
    except urllib.error.HTTPError as e:
        return f"{n}: bot NOT started, HTTP {e.code} {e.read().decode()[:200]}"


def patch(n):
    import base64 as b64
    req = urllib.request.Request(HOST + f"/a/changes/{n}/revisions/current/patch",
                                 headers=AUTH)
    with urllib.request.urlopen(req, timeout=60) as r:
        return b64.b64decode(r.read()).decode(errors="replace")


def render(r, full=False):
    flags = ("M" if r["mine"] else "-") + ("A" if r["attention"] else "-")
    out = [f"{r['number']} [{flags}] ps{r['patchset']} {r['branch']} {r['owner']}: "
           f"{r['subject'] if full else r['subject'][:60]}",
           f"    bot={r['bot']} precheck={r['precheck']} mergeable={r['mergeable']} "
           f"unresolved={r['unresolved']} open_parents={r['open_parents']} -> {r['hint']}"]
    if not full:
        return "\n".join(out)
    out += [f"    {r['url']}  sha={r['sha'][:12]} parent={[p[:12] for p in r['parent_sha']]}",
            f"    children={r['open_children']} reviewers={r['reviewers']}",
            f"    attention: {r['attention_set']}",
            f"    votes: {r['votes']}",
            f"    bot jobs: {r['bot_jobs']}",
            "    commit message:"] + ["      " + l for l in r["commit_message"].splitlines()]
    out.append("    files: " + ", ".join(f"{f} ({d})" for f, d in r["files"].items()))
    for t in r["unresolved_threads"]:
        out.append(f"    UNRESOLVED {t['file']}:{t['line']} ps{t['patchset']} reply_to={t['reply_to']}")
        for c in t["comments"]:
            out.append(f"      <{c['author']}> " + c["text"].replace("\n", "\n        "))
    if r.get("precheck_failure"):
        out.append("    PRECHECK FAILURE: " + r["precheck_failure"][:1500].replace("\n", "\n      "))
    out.append("    recent messages:")
    for m in r["messages"][-5:]:
        out.append(f"      ps{m['ps']} {m['date']} {m['author']}: " + m["text"][:400].replace("\n", " | "))
    return "\n".join(out)


def main():
    args = sys.argv[1:]
    if "--start-bot" in args:
        for n in args[args.index("--start-bot") + 1:]:
            print(start_bot(n))
        return
    if "--patch" in args:
        print(patch(args[args.index("--patch") + 1]))
        return
    attention = query("attention:self status:open")
    mine = query("owner:self status:open")
    if isinstance(attention, dict) or isinstance(mine, dict):
        sys.exit(f"query failed: {attention if isinstance(attention, dict) else mine}")
    mine_nums = {c["_number"] for c in mine}
    todo = {c["_number"]: c for c in attention + mine}
    with cf.ThreadPoolExecutor(8) as ex:
        results = dict(zip(todo, ex.map(analyse, todo.values())))
    rows = []
    for n, i in results.items():
        is_mine = n in mine_nums
        i["mine"] = is_mine
        i["attention"] = any(c["_number"] == n for c in attention)
        i["hint"] = hint(i, is_mine)
        rows.append(i)
    rows.sort(key=lambda r: (not r["mine"], r["number"]))
    if "--only" in sys.argv:
        want = set()
        for a in sys.argv[sys.argv.index("--only") + 1:]:
            if a.startswith("--"):
                break
            want.add(int(a))
        rows = [r for r in rows if r["number"] in want]
    elif "--all" not in sys.argv:
        rows = [r for r in rows if not r["hint"].startswith("skip")]
        print(f"({len(results) - len(rows)} stale/WIP changes of mine skipped; --all shows them)", file=sys.stderr)
    if "--json" in sys.argv:
        print(json.dumps(rows, indent=1))
        return
    for r in rows:
        print(render(r, full="--full" in sys.argv))


if __name__ == "__main__":
    main()
